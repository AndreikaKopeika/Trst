const ease = (t) => t * t * (3 - 2 * t);

// Значение дорожки на прогрессе p: для чисел — плавно между соседними ключами, для строк — ступенькой
export function sample(keys, track, p) {
  let a = null, b = null;
  for (const k of keys) {
    if (k[track] === undefined) continue;
    if (k.t <= p) a = k; else { b = k; break; }
  }
  if (!a) return b ? b[track] : undefined;
  const va = a[track];
  if (!b || typeof va === 'string') return va;
  const u = ease(Math.min(1, Math.max(0, (p - a.t) / (b.t - a.t))));
  const vb = b[track];
  if (typeof va === 'number') return va + (vb - va) * u;
  return { a: va, b: vb, u };
}
